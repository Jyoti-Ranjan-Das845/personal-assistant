"""Write the Omnigent agent configs for the agents the person talks to.

Each config freezes that agent's instructions (charter, constitution and, for
the front-door agents, the approved core profile) into its prompt, and gives
it one tool server, system/tools_server.py, started with its role. It gets no
operating-system environment, so Omnigent's Claude harness runs it without
the CLI's own shell and file tools: the tool server is all it can touch.
Each front-door agent also carries the worker as a sub-agent: native Claude Code
(harness claude-native), which has the person's own app connections and the
web, guarded in code by system/omnigent_policies.worker_guard through the hooks
Omnigent installs in every native session. The front-door agents stay on the
claude-sdk harness, so their only tools are the tool server and Omnigent's
session tools for dispatching workers. The analyst, advisor, challenger,
builder, policy checker and quarantine reader are not Omnigent agents; the tool
server runs them in fresh sessions.

Omnigent imports the worker guard by its dotted path, so start Omnigent with the
project root on PYTHONPATH (see README).
Re-run this after any approved change to the kit or the core profile.

    python3 scripts/build_agents.py
"""

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from system import prompts  # noqa: E402
from system.config import AGENTS, MODELS, READABLE, RECORD, ROOT, STATE, TEMPLATE_RECORD, WORKSPACE  # noqa: E402
from system.record import Record  # noqa: E402


REQUIRED_PROFILE_SECTIONS = [
    r"## Who \w+ (is|are)",
    r"## Values, in priority order",
    r"## Tie-breakers",
    r"## Blind spots",
    r"## How \w+ wants? answers",
    r"## Topics not to guess about",
    r"## Machine-readable rules",
]

DESCRIPTIONS = {
    "chief_of_staff": "The person's front door. Advises as they would, in the honest-broker tradition.",
    "interviewer": "Builds the record: new decisions before their outcome, and outcome reviews.",
    "curator": "The weekly review of the record: stale facts, due reviews, conflicts and drift.",
    "onboarding": "Onboarding in one conversation: scope, gather from the person's sources, prepare, then short interview sessions.",
    "worker": "Native Claude Code with the person's app connections and the web: finds, checks and drafts; never acts in their name.",
    "case_finder": "Native Claude Code that reads the person's approved sources and writes digests of real cases for onboarding.",
    "preparer": "Turns the case finder's digests into an interview guide and sets up the onboarding ledger.",
}


def check_profile(text: str) -> list[str]:
    return [s for s in REQUIRED_PROFILE_SECTIONS if not re.search(s, text)]


def indent(text: str, spaces: int) -> str:
    pad = " " * spaces
    return "\n".join(pad + line if line else "" for line in text.splitlines())


WORKER_MODEL = "claude-opus-5-5"  # it reads strangers' text, so it gets the strongest model


def tool_server(role: str, approval_cards: bool) -> str:
    args = [str(ROOT / "system/tools_server.py"), "--role", role, "--record", str(RECORD), "--state", str(STATE)]
    if approval_cards:
        args.append("--approval-cards")
    return ("  pa:\n"
            "    type: mcp\n"
            f"    command: {sys.executable}\n"
            f"    args: [{', '.join(args)}]\n")


def write_native(bundle: Path, name: str, prompt: str) -> Path:
    if len(prompt.encode()) > prompts.NATIVE_PROMPT_LIMIT:  # tmux refuses a longer launch command, and the agent never starts
        raise SystemExit(f"the {name} prompt is {len(prompt.encode())} bytes; a native agent's must stay under "
                         f"{prompts.NATIVE_PROMPT_LIMIT}. Shorten its charter.")
    """A native Claude Code sub-agent (the worker or the case finder) inside a bundle, guarded in code."""
    out_dir = bundle / "agents" / name
    out_dir.mkdir(parents=True, exist_ok=True)
    WORKSPACE.mkdir(exist_ok=True)
    out = out_dir / "config.yaml"
    out.write_text(
        f"# GENERATED by scripts/build_agents.py. Edit kit/charters/{name}.md, then rebuild.\n"
        "spec_version: 1\n"
        f"name: {name}\n"
        f"description: {json.dumps(DESCRIPTIONS[name])}\n"
        "\n"
        "executor:\n"
        "  type: omnigent\n"
        "  config:\n"
        "    harness: claude-native\n"
        f"    model: {WORKER_MODEL}\n"
        "    # headless: nobody answers Claude Code's own prompts, so the guard below decides\n"
        "    permission_mode: auto\n"
        "\n"
        "os_env:\n"
        "  type: caller_process\n"
        f"  cwd: {WORKSPACE}\n"
        "  sandbox:\n"
        "    type: none\n"
        "\n"
        "guardrails:\n"
        "  ask_timeout: 3600   # an unanswered request to act is refused after an hour\n"
        "  policies:\n"
        "    worker_guard:\n"
        "      type: function\n"
        "      on: [tool_call]\n"
        "      function:\n"
        "        path: system.omnigent_policies.worker_guard\n"
        f"        arguments: {{project_root: {ROOT}, workspace: {WORKSPACE}, record_dir: {RECORD}, readable: {json.dumps(READABLE)}}}\n"
        "    blast_radius:\n"
        "      type: function\n"
        "      on: [tool_call]\n"
        "      function:\n"
        "        path: omnigent.inner.nessie.policies.blast_radius\n"
        "        arguments: {gate_pushes: true}\n"
        "\n"
        "prompt: |\n"
        f"{indent(prompt, 2)}\n",
        encoding="utf-8",
    )
    return out


def write_worker(bundle: Path, prompt: str) -> Path:
    return write_native(bundle, "worker", prompt)


def write_sdk(out_dir: Path, name: str, role: str, prompt: str, subagents: list[str], approval_cards: bool) -> Path:
    """An agent on the claude-sdk harness: no shell or files, only its tool server and Omnigent's session tools."""
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / "config.yaml"
    guardrails = ""
    if subagents or approval_cards:
        guardrails = "guardrails:\n  ask_timeout: 86400   # an approval card waits for the person for a day\n  policies:\n"
        if subagents:
            guardrails += ("    spawn_bounds:\n"
                           "      type: function\n"
                           "      function:\n"
                           "        path: omnigent.inner.nessie.policies.spawn_bounds\n"
                           "        arguments: {max_dispatches_per_turn: 4, dispatch_tools: [sys_session_send, sys_session_create]}\n")
        if approval_cards:
            guardrails += ("    person_approves:\n"
                           "      type: function\n"
                           "      on: [tool_call]\n"
                           "      function:\n"
                           "        path: system.omnigent_policies.person_approves\n"
                           f"        arguments: {{record_dir: {RECORD}}}\n")
        guardrails += "\n"
    out.write_text(
        "# GENERATED by scripts/build_agents.py. Edit kit/ or record/, then rebuild.\n"
        "spec_version: 1\n"
        f"name: {name}\n"
        f"description: {json.dumps(DESCRIPTIONS[name])}\n"
        "\n"
        "executor:\n"
        "  type: omnigent\n"
        "  config:\n"
        "    harness: claude-sdk\n"
        f"    model: {MODELS[role]}\n"
        "\n"
        "async: true\n"
        "cancellable: true\n"
        "\n"
        "tools:\n"
        "  timeout: 3000\n"
        + (f"  agents: [{', '.join(subagents)}]   # dispatched with sys_session_send\n" if subagents else "")
        + tool_server(role, approval_cards)
        + "\n"
        + guardrails
        + "prompt: |\n"
        f"{indent(prompt, 2)}\n",
        encoding="utf-8",
    )
    return out


def write_agent(role: str, prompt: str) -> Path:
    """A front-door agent with the native worker as its sub-agent."""
    return write_sdk(AGENTS / role, role, role, prompt, ["worker"], approval_cards=True)


def main() -> None:
    if not RECORD.exists():  # a record kept outside the pack starts from the empty templates
        shutil.copytree(TEMPLATE_RECORD, RECORD, ignore=shutil.ignore_patterns(".git", "_proposals", "_working", "_drafts"))
        subprocess.run(["git", "init", "-q"], cwd=RECORD)
    record = Record(RECORD)
    missing = check_profile(record.profile())
    if missing:
        raise SystemExit(f"core_profile.md is missing sections: {', '.join(missing)}")
    if "TEMPLATE:" in record.profile():
        print("note: the record is still the empty template; start with: pa onboard")
    worker_prompt = prompts.build("worker", record, with_date=False)
    for role in ("chief_of_staff", "curator"):  # the interviewer is the onboarding agent below
        out = write_agent(role, prompts.build(role, record, with_date=False))
        print(f"wrote {out.relative_to(ROOT)}")
        print(f"wrote {write_worker(out.parent, worker_prompt).relative_to(ROOT)}")

    # Onboarding: the interviewer holds one conversation; the case finder, preparer and worker work behind it.
    bundle = AGENTS / "onboarding"
    out = write_sdk(bundle, "onboarding", "interviewer", prompts.build("interviewer", record, with_date=False),
                    ["case_finder", "preparer", "worker"], approval_cards=True)
    print(f"wrote {out.relative_to(ROOT)}")
    for name in ("case_finder", "worker"):
        print(f"wrote {write_native(bundle, name, prompts.build(name, record, with_date=False)).relative_to(ROOT)}")
    prep = write_sdk(bundle / "agents" / "preparer", "preparer", "preparer", prompts.build("preparer", record, with_date=False),
                     [], approval_cards=False)
    print(f"wrote {prep.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
